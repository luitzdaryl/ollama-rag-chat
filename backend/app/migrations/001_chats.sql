-- 001_chats.sql: conversations and their messages

CREATE TABLE chats (
    id          text PRIMARY KEY,                       -- generated by the browser, e.g. chat_1730000000000_ab12
    title       text NOT NULL DEFAULT 'New Chat',
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE messages (
    chat_id       text    NOT NULL REFERENCES chats (id) ON DELETE CASCADE,
    position      integer NOT NULL,                      -- 0, 1, 2, ... order within the chat
    role          text    NOT NULL CHECK (role IN ('user', 'assistant')),
    content       text    NOT NULL DEFAULT '',
    sources       jsonb   NOT NULL DEFAULT '[]'::jsonb,  -- retrieved passages: [{filename, score, text, ...}]
    search_query  text,
    rerank_note   text,
    model_name    text,
    elapsed       text,
    sent_at       timestamptz,
    stopped       boolean NOT NULL DEFAULT false,
    is_error      boolean NOT NULL DEFAULT false,
    PRIMARY KEY (chat_id, position)
);

CREATE INDEX chats_updated_at_idx ON chats (updated_at DESC);